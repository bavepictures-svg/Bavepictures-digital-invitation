#!/usr/bin/env python3
"""Bundle the Ivory Botanical Gold theme into generator/bundled-templates.js.

WHY: the generator must work by double-clicking generator/index.html (file://), where browsers
block fetch() of other files. So the theme's files are embedded (base64) in bundled-templates.js,
and the zip is built purely in memory.

WHEN TO RUN: every time a file listed in template/ivory-botanical-gold/manifest.json changes
(or the list itself, or the default music):

    python3 generator/build-bundle.py          # rebuild generator/bundled-templates.js
    python3 generator/build-bundle.py --check  # exit 1 if the bundle is out of date (no write)

Pure standard library — no install needed.
"""
import base64, hashlib, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
THEME = os.path.join(HERE, "..", "template", "ivory-botanical-gold")
OUT = os.path.join(HERE, "bundled-templates.js")


def build():
    manifest = json.load(open(os.path.join(THEME, "manifest.json"), encoding="utf-8"))
    paths = list(manifest["files"]) + [manifest["defaultMusic"]]
    files, hashes = {}, {}
    for p in paths:
        data = open(os.path.join(THEME, p), "rb").read()
        files[p] = base64.b64encode(data).decode("ascii")
        hashes[p] = hashlib.sha256(data).hexdigest()
    bundle = {
        "theme": manifest["theme"],
        "defaultMusic": manifest["defaultMusic"],
        "files": list(manifest["files"]),
        "sha256": hashes,
        "data": files,
    }
    js = ("/* GENERATED by generator/build-bundle.py from template/ivory-botanical-gold/ — do not edit by hand.\n"
          "   Re-run `python3 generator/build-bundle.py` after changing the theme. */\n"
          "window.THEME_BUNDLES = window.THEME_BUNDLES || {};\n"
          "window.THEME_BUNDLES[%s] = %s;\n") % (json.dumps(manifest["theme"]), json.dumps(bundle, separators=(",", ":")))
    return js, hashes


if __name__ == "__main__":
    js, hashes = build()
    if "--check" in sys.argv:
        ok = os.path.exists(OUT) and open(OUT, encoding="utf-8").read() == js
        print("bundle up to date" if ok else "bundle OUT OF DATE — run: python3 generator/build-bundle.py")
        sys.exit(0 if ok else 1)
    open(OUT, "w", encoding="utf-8").write(js)
    print("wrote %s — %d files, %.1f MB" % (os.path.relpath(OUT), len(hashes), len(js) / 1048576))
